/**
 * B13. Regenerates the bundled world coastline from Natural Earth.
 *
 *   node scripts/generate-world-outline.mjs
 *
 * **Why a generator and a committed output, rather than either extreme.** The
 * outline that shipped first was typed by hand and looked like it: a status page
 * is not the place for an approximation of Africa. But reading the source data
 * at build time would put a dependency between `npm run build` and a package's
 * internals, and reading it at RUNTIME would mean shipping a megabyte of
 * TopoJSON to every visitor for a backdrop.
 *
 * So the data is converted once, here, and the result is committed. `world-atlas`
 * and `topojson-client` are devDependencies: nothing at runtime imports either.
 *
 * Source: Natural Earth 1:110m land, which is public domain, packaged by
 * `world-atlas` (ISC). Attribution is carried in the generated file's header.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { feature } from "topojson-client";
import topology from "world-atlas/land-110m.json" with { type: "json" };

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "regions", "worldLand.ts");

/**
 * Decimal places kept per coordinate.
 *
 * The map is 1000px for 360 degrees, so one pixel is 0.36 degrees and one
 * decimal place is already a third of a pixel. A second decimal would triple the
 * file for detail no screen can show.
 */
const PRECISION = 1;

/**
 * Rings smaller than this (in square degrees) are dropped.
 *
 * At world scale they are one or two pixels and read as rendering noise rather
 * than as islands. The threshold is deliberately low: it removes specks, not
 * countries.
 */
const MIN_AREA = 0.6;

const round = (n) => Number(n.toFixed(PRECISION));

/** Shoelace area, unsigned. Only used to decide whether a ring is visible. */
function area(ring) {
  let sum = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    sum += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  }
  return Math.abs(sum / 2);
}

const land = feature(topology, topology.objects.land);
const polygons = land.type === "FeatureCollection" ? land.features : [land];

const rings = [];
for (const item of polygons) {
  const geometry = item.geometry ?? item;
  const coords = geometry.type === "MultiPolygon" ? geometry.coordinates.flat() : geometry.coordinates;
  for (const ring of coords) {
    if (ring.length < 4) continue;
    if (area(ring) < MIN_AREA) continue;

    /**
     * **Unwrapped across the antimeridian before anything else.**
     *
     * Natural Earth stores Afro-Eurasia as ONE ring, and it crosses 180 at
     * Chukotka. Left alone, the point after the crossing jumps from +179 to
     * -179, and a renderer draws a straight line back across the entire map:
     * a horizontal streak through the Pacific, Africa and the Atlantic. Fiji
     * and Wrangel Island do the same thing on a smaller scale.
     *
     * Unwrapping keeps the ring continuous by letting longitude run past 180
     * instead of jumping. The renderer then draws a second copy shifted by a
     * whole world width, and the SVG viewBox clips whatever falls outside - so
     * the far east of Russia appears on the left edge where it belongs, with no
     * polygon clipping arithmetic anywhere.
     */
    const unwrapped = [];
    let previousLon = null;
    let offset = 0;
    for (const [lon, lat] of ring) {
      if (previousLon !== null) {
        const step = lon - previousLon;
        if (step > 180) offset -= 360;
        else if (step < -180) offset += 360;
      }
      previousLon = lon;
      unwrapped.push([lon + offset, lat]);
    }

    // Flattened to [lon, lat, lon, lat, ...]: half the brackets of a nested
    // array for the same numbers, which matters when it is a bundled constant.
    const flat = [];
    let last = null;
    for (const [lon, lat] of unwrapped) {
      const x = round(lon);
      const y = round(lat);
      // Rounding collapses neighbouring points; keeping both would draw a
      // zero-length segment for every one of them.
      if (last && last[0] === x && last[1] === y) continue;
      flat.push(x, y);
      last = [x, y];
    }
    if (flat.length >= 8) rings.push(flat);
  }
}

rings.sort((a, b) => b.length - a.length);

const header = `// GENERATED by scripts/generate-world-outline.mjs. Do not edit by hand.
//
// Natural Earth 1:110m land, public domain, via the \`world-atlas\` package.
// Flattened to [lon, lat, lon, lat, ...] per ring and rounded to ${PRECISION}
// decimal place, which is a third of a pixel at this map's scale.
//
// Rings are ordered largest first, so a renderer that ever needs to cut the list
// short keeps the continents.

/** Closed rings of land, as flat [lon, lat] pairs. */
export const LAND_RINGS: readonly (readonly number[])[] = [
${rings.map((r) => `  [${r.join(",")}],`).join("\n")}
];
`;

fs.writeFileSync(OUT, header);
const bytes = Buffer.byteLength(header);
console.log(`wrote ${OUT}`);
console.log(`  rings: ${rings.length}`);
console.log(`  points: ${rings.reduce((n, r) => n + r.length / 2, 0)}`);
console.log(`  size: ${(bytes / 1024).toFixed(1)} KB`);
